import clsx from 'clsx';
import { Lock, SlidersHorizontal, Sparkles, Users, X } from 'lucide-react';
import { useEffect, useRef } from 'react';
import { MEAL_SLOTS } from '../../../shared/types';
import { SLOT_META } from '../../lib/format';
import { usePlan } from '../../store/plan';
import { usePrefs } from '../../store/prefs';
import { useShop } from '../../store/shop';
import { Button } from '../ui/Button';
import { Stepper } from '../ui/Stepper';

const EXAMPLES = [
  'High-protein, no seafood, quick lunches, ~$120 budget',
  'Vegetarian comfort food for a family of 4',
  'Low-carb with 20-minute dinners',
  'Cheap and cheerful, under $80',
  'Mediterranean, lots of veggies, batch-prep friendly',
];

export function PlannerPanel({ onOpenPrefs }: { onOpenPrefs: () => void }) {
  const { prefs, setPrefs, setSlot, draftRequest, setDraftRequest } = usePrefs();
  const { plan, status, generate, cancel, setWeekServings } = usePlan();
  const aiLive = useShop((s) => s.config?.ai.live);
  const textRef = useRef<HTMLTextAreaElement>(null);

  const lockedCount = plan ? plan.days.reduce((n, d) => n + Object.values(d.meals).filter((m) => m?.locked).length, 0) : 0;
  const activeSlots = MEAL_SLOTS.filter((s) => prefs.slots[s]);
  const servings = plan?.weekServings ?? prefs.householdServings;
  const prefSummary = [
    prefs.diets.length && `${prefs.diets.length} diet${prefs.diets.length > 1 ? 's' : ''}`,
    prefs.allergies.length && `${prefs.allergies.length} allerg${prefs.allergies.length > 1 ? 'ies' : 'y'}`,
    `$${prefs.weeklyBudget}/wk`,
    `≤${prefs.maxCookMinutes} min`,
  ].filter(Boolean).join(' · ');

  // Auto-grow the prompt box.
  useEffect(() => {
    const el = textRef.current;
    if (!el) return;
    el.style.height = 'auto';
    el.style.height = `${Math.min(el.scrollHeight, 160)}px`;
  }, [draftRequest]);

  const submit = () => !status.generating && activeSlots.length && generate(draftRequest);

  return (
    <section className="card relative overflow-hidden p-5 sm:p-7">
      {/* Decorative food-colored blobs */}
      <div className="pointer-events-none absolute -right-16 -top-20 h-56 w-56 rounded-full bg-butter-300/40 blur-3xl dark:bg-butter-400/10" />
      <div className="pointer-events-none absolute -bottom-24 right-40 h-48 w-48 rounded-full bg-avocado-300/30 blur-3xl dark:bg-avocado-400/10" />

      <div className="relative">
        <div className="flex flex-wrap items-center gap-2">
          <h1 className="text-2xl font-extrabold tracking-tight sm:text-[28px]">What are we cooking this week?</h1>
          <span
            className={clsx(
              'chip',
              aiLive ? 'bg-berry-100 text-berry-700 dark:bg-berry-400/15 dark:text-berry-300' : 'bg-surface-2 text-muted',
            )}
            title={aiLive ? 'Plans are generated by Claude' : 'No Anthropic key yet: plans come from the built-in recipe library'}
          >
            <Sparkles size={12} /> {aiLive ? 'Claude' : 'Demo recipes'}
          </span>
        </div>
        <p className="mt-1 text-sm text-muted">Describe your week in plain words. We'll plan it, list it, and price it.</p>

        <div className="mt-4 rounded-3xl border border-line bg-surface-2/70 p-2 transition focus-within:border-tomato-300 focus-within:bg-surface focus-within:shadow-[0_0_0_4px_rgb(255_90_54/0.12)]">
          <textarea
            ref={textRef}
            rows={2}
            value={draftRequest}
            onChange={(e) => setDraftRequest(e.target.value)}
            onKeyDown={(e) => {
              if (e.key === 'Enter' && (e.metaKey || e.ctrlKey)) submit();
            }}
            placeholder="High-protein, no seafood, quick lunches, ~$120 budget"
            className="block w-full resize-none bg-transparent px-3 py-2 text-[15px] font-medium leading-relaxed placeholder:text-muted focus:outline-none"
            aria-label="Describe your week"
          />
          <div className="flex flex-wrap items-center justify-between gap-2 px-1 pb-1">
            <div className="no-scrollbar -mx-1 flex min-w-0 flex-1 basis-64 gap-1.5 overflow-x-auto px-1">
              {EXAMPLES.map((ex) => (
                <button
                  key={ex}
                  onClick={() => setDraftRequest(ex)}
                  className="shrink-0 rounded-full bg-surface px-3 py-1 text-xs font-semibold text-ink-soft ring-1 ring-line transition hover:text-ink hover:ring-ink/20"
                >
                  {ex}
                </button>
              ))}
            </div>
            {status.generating ? (
              <Button variant="secondary" size="lg" onClick={cancel}>
                <X size={16} /> Cancel
              </Button>
            ) : (
              <Button variant="primary" size="lg" onClick={submit} disabled={!activeSlots.length} className="ml-auto">
                <Sparkles size={17} />
                {plan ? 'Regenerate week' : 'Generate my week'}
                {lockedCount > 0 && (
                  <span className="ml-1 inline-flex items-center gap-0.5 rounded-full bg-white/20 px-2 py-0.5 text-xs">
                    <Lock size={11} /> {lockedCount} kept
                  </span>
                )}
              </Button>
            )}
          </div>
        </div>

        <div className="mt-4 flex flex-wrap items-center gap-x-5 gap-y-3">
          <div className="flex flex-wrap items-center gap-1.5">
            <span className="mr-1 text-xs font-bold uppercase tracking-wide text-muted">Meals / day</span>
            {MEAL_SLOTS.map((slot) => {
              const on = prefs.slots[slot];
              return (
                <button
                  key={slot}
                  onClick={() => setSlot(slot, !on)}
                  aria-pressed={on}
                  className={clsx(
                    'inline-flex items-center gap-1.5 rounded-full border px-3 py-1.5 text-sm font-semibold transition active:scale-95',
                    on ? 'border-transparent ' + SLOT_META[slot].tone : 'border-dashed border-line text-muted line-through decoration-2 hover:text-ink',
                  )}
                >
                  <span className={clsx(!on && 'grayscale')}>{SLOT_META[slot].emoji}</span>
                  {SLOT_META[slot].label}
                </button>
              );
            })}
          </div>

          <div className="flex items-center gap-2">
            <span className="flex items-center gap-1 text-xs font-bold uppercase tracking-wide text-muted">
              <Users size={13} /> Servings
            </span>
            <Stepper
              label="Servings for the whole week"
              value={servings}
              onChange={(n) => {
                setPrefs({ householdServings: Math.min(20, Math.max(1, n)) });
                if (plan) setWeekServings(n);
              }}
            />
          </div>

          <button onClick={onOpenPrefs} className="inline-flex items-center gap-1.5 text-sm font-semibold text-ink-soft transition hover:text-tomato-600 dark:hover:text-tomato-400">
            <SlidersHorizontal size={15} />
            {prefSummary}
          </button>
        </div>
      </div>
    </section>
  );
}
